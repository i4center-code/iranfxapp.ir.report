/* ---------- بومی‌سازی اعداد و علائم برای هر زبان ---------- */
const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹";
const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";

export function localize(str: string, lang: LangCode): string {
  /* ابتدا نرمال‌سازی به لاتین */
  let s = str
    .replace(/[۰-۹]/g, (d) => String(FA_DIGITS.indexOf(d)))
    .replace(/[٠-٩]/g, (d) => String(AR_DIGITS.indexOf(d)))
    .replace(/٬/g, ",")
    .replace(/٫/g, ".")
    .replace(/٪/g, "%");
  if (lang === "fa" || lang === "ps" || lang === "ur") {
    s = s
      .replace(/[0-9]/g, (d) => FA_DIGITS[+d])
      .replace(/,/g, "٬")
      .replace(/\./g, "٫")
      .replace(/%/g, "٪")
      .replace(/؛/g, "،");
  } else if (lang === "ar") {
    s = s
      .replace(/[0-9]/g, (d) => AR_DIGITS[+d])
      .replace(/,/g, "٬")
      .replace(/\./g, "٫")
      .replace(/%/g, "٪")
      .replace(/؛/g, "،");
  } else {
    s = s.replace(/؛/g, ",");
  }
  return s;
}

