/* ---------- context ---------- */
type I18nValue = {
  lang: LangCode;
  dir: "rtl" | "ltr";
  setLang: (l: LangCode) => void;
  t: (key: string, fallback?: string) => string;
  loc: (s: string | number) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function isValidLang(v: string | null): v is LangCode {
  return !!v && LOCALES.some((l) => l.code === v);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(() => {
    try {
      const saved = localStorage.getItem("iranfx-lang");
      return isValidLang(saved) ? saved : "fa";
    } catch {
      return "fa";
    }
  });

  const meta = LOCALES.find((l) => l.code === lang) ?? LOCALES[0];

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      localStorage.setItem("iranfx-lang", l);
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    const m = LOCALES.find((l) => l.code === lang) ?? LOCALES[0];
    document.documentElement.lang = m.code;
    document.documentElement.dir = m.dir;
  }, [lang]);

  const t = useCallback(
    (key: string, fallback?: string) => {
      const d = MESSAGES[lang];
      /* بومی‌سازی اعداد، جداکننده‌ها و تبدیل «؛» به «،» */
      return localize((d && d[key]) || fa[key] || fallback || key, lang);
    },
    [lang]
  );

  const loc = useCallback((s: string | number) => localize(String(s), lang), [lang]);

  const value = useMemo(() => ({ lang, dir: meta.dir, setLang, t, loc }), [lang, meta.dir, setLang, t, loc]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n باید داخل I18nProvider استفاده شود");
  return ctx;
}

/* ---------- تم ---------- */
export function useTheme() {
  const [theme, setThemeState] = useState<"dark" | "light">(() =>
    typeof document !== "undefined" && document.documentElement.dataset.theme === "light" ? "light" : "dark"
  );
  const setTheme = useCallback((t: "dark" | "light") => {
    setThemeState(t);
    document.documentElement.dataset.theme = t;
    try {
      localStorage.setItem("iranfx-theme", t);
    } catch {
      /* ignore */
    }
  }, []);
  return { theme, setTheme };
}
